def hex_rgb(rgb):
    return "#%02x%02x%02x" % rgb


def build():
    out = {}
    for code, (rgb, en, es, den, des, biome) in CLASSES.items():
        assert biome in BIOMES, biome
        out[code] = {"color": hex_rgb(rgb), "group": code[0], "en": en, "es": es,
                     "desc_en": den, "desc_es": des, "biome": biome}
    out["biomes"] = {bid: {"color": c, "en": en, "es": es, "desc_en": den, "desc_es": des, "emoji": emo}
                     for bid, (c, en, es, den, des, emo) in BIOMES.items()}
    return out


if __name__ == "__main__":
    data = build()
    with open(sys.argv[1], "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("wrote", sys.argv[1], len(data) - 1, "classes,", len(data["biomes"]), "biomes")
